#!/usr/bin/env node
/**
 * Emits `src/app/themes.generated.css` from the theme registry
 * (`src/lib/themes/registry.ts`), the single source of truth.
 *
 * One block per theme per mode:
 *   html[data-theme="ocean"]        { …light tokens… }
 *   html[data-theme="ocean"].dark   { …dark tokens… }
 *
 * The `[data-theme]` attribute selector beats `:root`, and the combined
 * `.dark` selector beats `html[data-theme]` alone, so the hand-written
 * `:root` / `.dark` blocks in globals.css remain a no-JS fallback while
 * generated blocks win whenever a theme attribute is present.
 *
 * Run with `pnpm themes:generate` after editing the registry.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, paletteToCssVars } from '../src/lib/themes/registry.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'app', 'themes.generated.css');

const DEFAULT_THEME = THEMES.find((t) => t.id === 'atlas') ?? THEMES[0];

const blocks = [
  // No-JS fallback: the atlas palette on bare :root / .dark. These lose to
  // any [data-theme] block (higher specificity), and dark always wins via
  // `html[data-theme].dark`.
  `:root {\n${paletteToCssVars(DEFAULT_THEME.light)}\n}`,
  `.dark {\n${paletteToCssVars(DEFAULT_THEME.dark)}\n}`,
];
for (const theme of THEMES) {
  blocks.push(`html[data-theme='${theme.id}'] {\n${paletteToCssVars(theme.light)}\n}`);
  blocks.push(`html[data-theme='${theme.id}'].dark {\n${paletteToCssVars(theme.dark)}\n}`);
}

const css = `/* Auto-generated by scripts/generate-theme-css.mjs — do not edit.\n   Edit src/lib/themes/registry.ts and run: pnpm themes:generate */\n\n${blocks.join('\n\n')}\n`;

writeFileSync(out, css);
console.log(`themes.generated.css — ${THEMES.length} themes × 2 modes written.`);
